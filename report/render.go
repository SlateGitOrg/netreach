// WriteJSON writes r as indented JSON.
func WriteJSON(w io.Writer, r Report) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	return enc.Encode(r)
}

// maxBlockedRows bounds the blocked-flow table per target in Markdown output
// (the JSON report always carries all of them).
const maxBlockedRows = 12

// WriteMarkdown renders r as a Markdown document.
func WriteMarkdown(w io.Writer, r Report) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# netreach report: %s\n\n", r.Snapshot)
	fmt.Fprintf(&b, "- Query: **%s** from `%s`\n", r.Query.Kind, r.Query.From)
	fmt.Fprintf(&b, "- Remote %s addresses: `%s`\n", r.Query.RemoteRole, r.Query.Remote)
	fmt.Fprintf(&b, "- Targets: %d analysed, %d reachable\n", r.Summary.Targets, r.Summary.Reachable)
	if len(r.Summary.Findings) > 0 {
		var parts []string
		for _, s := range []Severity{High, Medium, Low, Info} {
			if n := r.Summary.Findings[s]; n > 0 {
				parts = append(parts, fmt.Sprintf("%d %s", n, s))
			}
		}
		fmt.Fprintf(&b, "- Findings: %s\n", strings.Join(parts, ", "))
	}
	fmt.Fprintf(&b, "- Generated by netreach %s\n\n", r.Version)

	b.WriteString("## Summary\n\n| Target | Private IP | Public IP | TCP | UDP | Other protocols | Severity |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, t := range r.Targets {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", targetLabel(t), t.PrivateIP, dash(t.PublicIP),
			dash(t.Open.TCP), dash(t.Open.UDP), dash(protocolNames(t.Open.Other)), dash(string(t.Severity)))
	}
	word, column := "from", "Sources"
	if r.Query.RemoteRole == "destination" {
		word, column = "to", "Destinations"
	}
	for _, t := range r.Targets {
		writeTarget(&b, t, word, column)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func writeTarget(b *strings.Builder, t Target, word, column string) {
	fmt.Fprintf(b, "\n## %s\n\n", targetLabel(t))
	fmt.Fprintf(b, "Subnet `%s` in `%s`", t.Subnet, t.VPC)
	if t.Peer != "" {
		fmt.Fprintf(b, "; flows from `%s`", t.Peer)
	}
	b.WriteString(".\n\n")
	if !t.Reachable {
		b.WriteString("**Not reachable.**\n")
	} else {
		fmt.Fprintf(b, "| Severity | Protocol | Ports | %s | Initiator ports | Reason |\n|---|---|---|---|---|---|\n", column)
		for _, e := range t.Exposures {
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s |\n", e.Severity, e.Protocol, dash(e.Ports),
				e.RemoteSummary, dash(e.InitiatorPorts), e.Reason)
		}
		b.WriteString("\nPaths:\n")
		seen := map[string]bool{}
		for _, e := range t.Exposures {
			key := pathKey(e)
			if seen[key] {
				continue
			}
			seen[key] = true
			fmt.Fprintf(b, "\n- %s %s %s %s\n", e.Protocol, dash(e.Ports), word, e.RemoteSummary)
			for i, h := range e.Path {
				fmt.Fprintf(b, "  %d. `%s` %s: %s\n", i+1, h.Step, h.Component, h.Detail)
			}
		}
	}
	if len(t.Blocked) == 0 {
		return
	}
	b.WriteString("\nBlocked flows (deciding hop):\n\n| Step | Component | Detail | Flows |\n|---|---|---|---|\n")
	for i, x := range t.Blocked {
		if i == maxBlockedRows {
			fmt.Fprintf(b, "\n_%d more blocked classes in the JSON report._\n", len(t.Blocked)-maxBlockedRows)
			break
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", x.Step, x.Component, escapePipes(x.Detail), x.Flows)
	}
}

func pathKey(e Exposure) string {
	var sb strings.Builder
	sb.WriteString(e.Protocol + "|" + e.Ports + "|" + e.RemoteSummary)
	for _, h := range e.Path {
		sb.WriteString("|" + h.Detail)
	}
	return sb.String()
}

func targetLabel(t Target) string {
	label := "`" + t.ENI + "`"
	if t.Name != "" {
		label = t.Name + " " + label
	}
	if t.Instance != "" {
		label += " (" + t.Instance + ")"
	}
	return label
}

// protocolNames renders a protocol-number set string with well-known names.
func protocolNames(text string) string {
	s, err := interval.Parse(text)
	if err != nil || s.IsEmpty() {
		return text
	}
	return model.ProtocolName(s)
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func escapePipes(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
